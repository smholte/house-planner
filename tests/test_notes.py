"""View mode: notes in 2D and 3D, room notes, types and status, photos, the notes list with filters,
saved viewpoints, and export / import with the photos."""
from common import *
from PIL import Image, ImageDraw
NOTES = "() => window.__hp.app.project.notes.map(n => ({id: n.id, type: n.type, status: n.status, text: n.text, at: n.at, room: n.room, photos: n.photos.length}))"
photo = SHOTS + 'photo.jpg'
im = Image.new('RGB', (2400, 1600), (180, 200, 220)); ImageDraw.Draw(im).rectangle([600, 400, 1800, 1200], fill=(200, 120, 80)); im.save(photo, quality=90)
with sync_playwright() as p:
    b, pg = open_app(p)
    open_example(pg)
    pg.click('#mode-switch button[data-mode="view"]'); pg.wait_for_timeout(800)
    pg.click('#display-toggle button[data-mode="plan"]'); pg.wait_for_timeout(800)
    pg.click('#toolrail button[data-tool="note"]'); pg.wait_for_timeout(300)
    at = room_pt(pg, 'Keuken', 0.4, 0.5)
    pg.mouse.click(*to_screen(pg, *at)); pg.wait_for_timeout(600)
    n = pg.evaluate(NOTES)
    check('note placed in 2D (where clicked)', len(n) == 1 and abs(n[0]['at']['x'] - at[0]) < 0.05 and abs(n[0]['at']['y'] - at[1]) < 0.05, (n, at))
    pg.fill('#f-note-text', 'Where does the hood exhaust go?\nAsk the builder.'); pg.wait_for_timeout(400)
    pg.click('.note-types button.nt-question'); pg.wait_for_timeout(300)
    with pg.expect_file_chooser() as fc:
        pg.click('.inspector button:has-text("Add photo")')
    fc.value.set_files(photo)
    # making the photo smaller takes a few seconds in the test browser (software drawing)
    pg.wait_for_function("() => window.__hp.app.project.notes[0].photos.length > 0", timeout=20000); pg.wait_for_timeout(300)
    n = pg.evaluate(NOTES)[0]
    check('text, kind and photo', n['type'] == 'question' and n['photos'] == 1 and n['text'].startswith('Where'))
    aid = pg.evaluate("() => window.__hp.app.project.notes[0].photos[0]")
    check('photo made smaller', pg.evaluate("(id) => window.__hp.Assets.get(id).w", aid) == 1600)
    pg.keyboard.press('Escape'); pg.wait_for_timeout(300)
    pg.mouse.click(*room_screen(pg, 'Woonkamer', 0.25, 0.25)); pg.wait_for_timeout(600)
    pg.click('.inspector button:has-text("Add a note to this room")'); pg.wait_for_timeout(500)
    pg.fill('#f-note-text', 'Floor: oak, herringbone?'); pg.wait_for_timeout(300)
    pg.click('.inspector button:has-text("Mark as done")'); pg.wait_for_timeout(300)
    n = pg.evaluate(NOTES)
    check('room note, done', n[1]['room'] and n[1]['status'] == 'done')
    pg.click('#toolrail button[data-tool="notes"]'); pg.wait_for_timeout(500)
    c_open = pg.eval_on_selector_all('.note-list .note-row', 'els => els.length')
    pg.click('.notes-body .seg button:has-text("All")'); pg.wait_for_timeout(200)
    c_all = pg.eval_on_selector_all('.note-list .note-row', 'els => els.length')
    check('notes list filters (open 1, all 2)', c_open == 1 and c_all == 2, (c_open, c_all))
    pg.click('.note-list .note-row >> nth=0'); pg.wait_for_timeout(500)
    check('list row selects the note', pg.evaluate("() => window.__hp.app.selection.type") == 'note')
    pg.click('#dim-toggle button[data-dim="3d"]'); pg.wait_for_timeout(3000)
    check('pin in 3D', len(pg.query_selector_all('.pin3d')) == 1)
    pg.click('#toolrail button[data-tool="note"]'); pg.wait_for_timeout(200)
    pt = pg.evaluate("() => { const v = window.__hp.app.panes[0].view; const r = v.renderer.domElement.getBoundingClientRect(); for (let y = r.top + r.height * 0.5; y < r.bottom; y += 8) for (let x = r.left + r.width * 0.3; x < r.right; x += 8) { const h = v.firstHit({ clientX: x, clientY: y }); if (h && h.object.userData.roomId) return [x, y]; } return null; }")
    pg.mouse.click(pt[0], pt[1]); pg.wait_for_timeout(800)
    at = pg.evaluate(NOTES)[-1]['at']
    check('note placed in 3D on a floor', at and abs(at['h']) < 0.1 and at['y'] > 1, at)
    pg.keyboard.press('Escape')
    pg.click('#toolrail button[data-tool="views"]'); pg.wait_for_timeout(300)
    pg.click('.menu .mi:has-text("Save this view")'); pg.wait_for_timeout(300)
    pg.fill('#dlg-input', 'Kitchen corner'); pg.click('.dialog .btn.primary'); pg.wait_for_timeout(400)
    cam = pg.evaluate("() => window.__hp.app.panes[0].view.camera.position.toArray().map(x => +x.toFixed(2))")
    pg.click('#dim-toggle button[data-dim="2d"]'); pg.wait_for_timeout(1000)
    pg.click('#toolrail button[data-tool="views"]'); pg.wait_for_timeout(300)
    pg.click('.menu .mi:has-text("Kitchen corner")'); pg.wait_for_timeout(2500)
    check('viewpoint brings the 3D view back', pg.evaluate("() => window.__hp.app.view.dim") == '3d' and pg.evaluate("() => window.__hp.app.panes[0].view.camera.position.toArray().map(x => +x.toFixed(2))") == cam)
    text = pg.evaluate("async () => window.__hp.app.buildExport([window.__hp.app.project], false)")
    data = json.loads(text)
    check('export holds notes, photo and viewpoint', len(data['projects'][0]['project']['notes']) == 3 and aid in data['assets'] and len(data['projects'][0]['project']['viewpoints']) == 1)
    open(SHOTS + 'notes.house.json', 'w').write(text)
    with pg.expect_file_chooser() as fc:
        pg.evaluate("() => { window.__hp.app.importFlow(); }")
    fc.value.set_files(SHOTS + 'notes.house.json'); pg.wait_for_timeout(1500)
    pg.click('.dialog button:has-text("Keep both")'); pg.wait_for_timeout(4000)
    got = pg.evaluate("() => [window.__hp.app.project.notes.length, !!window.__hp.Assets.get(window.__hp.app.project.notes[0].photos[0])]")
    check('imported copy has the notes and the photo', got == [3, True], got)
    check('no page errors', not pg.errors, pg.errors)
    b.close()
sys.exit(summary())
